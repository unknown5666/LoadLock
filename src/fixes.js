// ===== Load-time corrections to the generated CAD crane bodies (gen/assets.js is generated and must not be edited by hand) =====
// Why this exists: pipeline/cad/norm2.py picks the "head sheave" (CRANE_DRAWINGS[key].tip = [s, n] in the boom frame, tipR = radius) as the
// circle with the greatest distance along the boom. Every telescopic head has TWO sheaves (a rear/top one and a front/lower one) whose s
// differs by only a few cm, so on some bodies it picked the rear/top sheave and the hook rope was drawn leaving the wrong pulley.
// The hook line, the radius geometry (R = Px + L·cosθ − n·sinθ in engine.js geoPivot/solveGeometry) and the rope in draw.js all follow `tip`,
// so correcting `tip` here fixes the picture and the numbers together (the rope position defines the radius).
//
// Each entry: tip/tipR = the correct FRONT (lower, outer) head sheave measured from the CAD circles, was = the value generated by norm2.py.
// A fix is only applied while the generated value still equals `was` (±2 cm), so regenerating gen/assets.js with a corrected norm2.py
// switches the matching entry off by itself; delete the table once the pipeline has been re-run.
const SHEAVE_FIX = {
  // rope was leaving the rear/top sheave, 1.6 m above the front one
  ltm1500: { was: [16.098, 0.055], tip: [16.089, -1.539], tipR: 0.291, why: 'norm2 picked the rear/top sheave (n +0.05) instead of the front/lower one' },
  // rear/top sheave picked, 0.84 m above the front one
  ztc300v: { was: [10.702, 0.223], tip: [10.688, -0.621], tipR: 0.176, why: 'norm2 picked the rear/top sheave (n +0.22) instead of the front/lower one' },
  // rear/top sheave picked, 1.30 m above the front one
  ltm1230: { was: [12.711, -0.163], tip: [12.696, -1.459], tipR: 0.254, why: 'norm2 picked the rear/top sheave (n -0.16) instead of the front/lower one' },
  // no sheave circle passed norm2's roundness test, so it fell back to the end of the boom casting (0.26 m ahead of the real front sheave, r defaulted to 0.30)
  ltm1160: { was: [13.226, -0.308], tip: [12.968, -0.331], tipR: 0.235, why: 'sheave circle was missed; tip fell back to the end of the head casting 0.26 m in front of the front sheave' },
  // the block has NO sheave drawn on its head; the generated tip (19.99, -1.16) floats 0.5 m ahead of and below the nose frame, so the rope hung in mid-air.
  // Approximation: the front/lower lug of the head frame (the lowest, most forward round pin the rope can hang from).
  ltm11200: { was: [19.99, -1.163], tip: [19.47, -0.64], tipR: 0.3, approx: true, why: 'no sheave in the block; tip was in empty space ahead of the head frame, moved to its front/lower lug' }
};
const SHEAVE_FIX_APPLIED = [];
function applySheaveFixes() {
  if (typeof CRANE_DRAWINGS === 'undefined') return SHEAVE_FIX_APPLIED;
  for (const k of Object.keys(SHEAVE_FIX)) {
    const d = CRANE_DRAWINGS[k], f = SHEAVE_FIX[k];
    if (!d || !Array.isArray(d.tip) || d._sheaveFixed) continue;
    if (Math.abs(d.tip[0] - f.was[0]) > 0.02 || Math.abs(d.tip[1] - f.was[1]) > 0.02) continue; // regenerated / already correct: leave it alone
    d._tip0 = d.tip.slice(); d._tipR0 = d.tipR; d._sheaveFixed = true;
    d.tip = f.tip.slice(); d.tipR = f.tipR;
    SHEAVE_FIX_APPLIED.push(k);
  }
  return SHEAVE_FIX_APPLIED;
}
applySheaveFixes();
